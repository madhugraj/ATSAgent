export function isCurrencyCode(code: string): boolean {
  return code.toUpperCase() in ISO_CURRENCIES;
}

export function isCountryCode(code: string): boolean {
  return code.toUpperCase() in ISO_COUNTRIES;
}

/** "INR" → "Indian rupee (INR)"; unknown codes pass through untouched. */
export function currencyLabel(code: string): string {
  const name = ISO_CURRENCIES[code.toUpperCase()];
  return name ? `${name} (${code.toUpperCase()})` : code;
}

export function countryName(code: string): string {
  return ISO_COUNTRIES[code.toUpperCase()] ?? code;
}
